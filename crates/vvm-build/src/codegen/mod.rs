    fn assert_generated_snapshot(
        actual_path: &Path,
        expected_path: &Path,
    ) -> Result<(), Box<dyn std::error::Error>> {
        let actual = std::fs::read_to_string(actual_path)?;
        let expected = std::fs::read_to_string(expected_path)?;

        assert_eq!(
            actual,
            expected,
            "generated artifact `{}` differs from its snapshot",
            actual_path.display()
        );

        assert!(
            actual.ends_with('\n'),
            "generated artifact must end with a newline: {}",
            actual_path.display()
        );

        assert!(
            !actual.contains('\r'),
            "generated artifact must use Unix newlines: {}",
            actual_path.display()
        );

        assert!(
            !actual.contains(env!("CARGO_MANIFEST_DIR")),
            "generated artifact contains a host checkout path: {}",
            actual_path.display()
        );

        Ok(())
    }

