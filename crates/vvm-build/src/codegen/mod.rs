    #[test]
    fn preserves_metadata_port_order() -> Result<(), Box<dyn std::error::Error>> {
        let width = BitWidth::new(NonZeroU32::MIN);

        let metadata = DutMetadata {
            name: "ordered".to_owned(),
            top_module: "ordered".to_owned(),
            ports: vec![
                scalar_port("z_input", PortDirection::Input, width, false),
                scalar_port("a_input", PortDirection::Input, width, false),
                scalar_port("m_output", PortDirection::Output, width, false),
            ],
        };

        let output = tempdir()?;
        let generated = generate(&metadata, "Vordered", output.path(), None)?;

        let header = std::fs::read_to_string(generated.cpp_header)?;

        let z_position = header.find("set_z_input").ok_or_else(|| {
            std::io::Error::new(std::io::ErrorKind::InvalidData, "missing set_z_input")
        })?;

        let a_position = header.find("set_a_input").ok_or_else(|| {
            std::io::Error::new(std::io::ErrorKind::InvalidData, "missing set_a_input")
        })?;

        let m_position = header.find("m_output").ok_or_else(|| {
            std::io::Error::new(std::io::ErrorKind::InvalidData, "missing m_output")
        })?;

        assert!(z_position < a_position);
        assert!(a_position < m_position);

        Ok(())
    }
